/// Builds device items with readable defaults.
public func item(
    _ id: String,
    _ filename: String,
    date: Int64 = 1_780_393_586,
    size: Int64 = 1_000,
    kind: MediaKind = .photo,
    role: ItemRole = .original,
    asset: String? = nil,
    parent: String? = nil
) -> DeviceItem {
    DeviceItem(
        deviceItemID: id, filename: filename, originalFilename: filename,
        captureDate: LocalTimestamp(secondsSince1970: date), size: size, kind: kind, role: role,
        assetID: asset, parentItemID: parent
    )
}

/// A device session that "downloads" by writing generated bytes, so tests get real files.
public final class FakeDeviceSession: DeviceSession, @unchecked Sendable {
    public let info: DeviceInfo
    public var items: [DeviceItem]
    public var listError: DeviceError?
    /// File contents per device item ID. Defaults to bytes derived from the ID, sized to the item.
    public var contents: [String: Data] = [:]
    /// Simulates a failure for these item IDs.
    public var downloadErrors: [String: DeviceError] = [:]
    /// Writes this many bytes fewer than the item's size, simulating a truncated transfer.
    public var truncate: [String: Int] = [:]
    public private(set) var closed = false
    public private(set) var downloaded: [String] = []

    public init(info: DeviceInfo, items: [DeviceItem]) {
        self.info = info
        self.items = items
    }

    public func listItems(progress: @escaping @Sendable (Int) -> Void) async throws(DeviceError) -> [DeviceItem] {
        if let listError { throw listError }
        progress(100)
        return items
    }

    public func download(
        _ item: DeviceItem, to directory: URL, as filename: String, progress: @escaping @Sendable (Int64) -> Void
    ) async throws(DeviceError) -> URL {
        if let error = downloadErrors[item.deviceItemID] { throw error }
        var data = contents[item.deviceItemID] ?? Self.bytes(for: item)
        if let missing = truncate[item.deviceItemID] { data = data.dropLast(missing) }
        let url = directory.appending(path: filename)
        do {
            try data.write(to: url, options: .withoutOverwriting)
        } catch {
            throw .downloadFailed(String(describing: error))
        }
        downloaded.append(item.deviceItemID)
        progress(Int64(data.count))
        return url
    }

    public func close() async {
        closed = true
    }

    public static func bytes(for item: DeviceItem) -> Data {
        let seed = Array("\(item.deviceItemID)-\(item.filename)".utf8)
        return Data((0..<Int(item.size)).map { seed[$0 % seed.count] &+ UInt8(truncatingIfNeeded: $0 / seed.count) })
    }
}

public final class FakeDeviceBrowser: DeviceBrowsing, @unchecked Sendable {
    public var devices: [DeviceInfo]
    public var session: FakeDeviceSession?
    public var openError: DeviceError?
    public private(set) var openCalls = 0

    public init(devices: [DeviceInfo] = [], session: FakeDeviceSession? = nil) {
        self.devices = devices
        self.session = session
    }

    public func connectedDevices() async -> [DeviceInfo] {
        devices
    }

    public func open(_ id: DeviceID, unlockTimeout: Duration) async throws(DeviceError) -> any DeviceSession {
        openCalls += 1
        if let openError { throw openError }
        guard let session, session.info.id == id else { throw .notFound }
        return session
    }
}

