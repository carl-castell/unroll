/// For tests that only plan and never write.
public struct NoWriters: DestinationOpening {
    public init() {}

    public func openForWriting(_ destination: ResolvedDestination) throws -> any DestinationWriter {
        throw SyncError.destinationUnwritable("tests don't write")
    }
}

public final class EventRecorder: @unchecked Sendable {
    private let lock = NSLock()
    private var recorded: [SyncEvent] = []

    public init() {}

    public var events: [SyncEvent] {
        lock.withLock { recorded }
    }

    public func record(_ event: SyncEvent) {
        lock.withLock { recorded.append(event) }
    }
}

